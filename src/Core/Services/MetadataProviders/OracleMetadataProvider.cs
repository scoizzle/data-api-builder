        /// <summary>
        /// Oracle-specific implementation to populate trigger metadata for a table.
        /// Stores the schema/table name mapping for later use by trigger-based
        /// identity column detection.
        /// </summary>
        public override async Task PopulateTriggerMetadataForTable(string entityName, string schemaName, string tableName, SourceDefinition sourceDefinition)
        {
            // Store the mapping for use in PopulateColumnDefinitionWithHasDefaultAndDbType.
            // GetColumnsAsync loads ALL_TRIGGERS only for tables staged here.
            string owner = string.IsNullOrEmpty(schemaName) ? GetDefaultSchemaName() : schemaName.ToUpperInvariant();
            string table = tableName.ToUpperInvariant();
            _sourceTableMap[sourceDefinition] = (owner, table);
            _triggerTables.Add((owner, table));
            await Task.CompletedTask;
        }

        /// <summary>
        /// Auto-generated linking entities (M:N multiple-create) have no config entity to declare
        /// exposed names, and Oracle folds unquoted identifiers to uppercase. Without defaults such
        /// a linking column (e.g. ROYALTY_PERCENTAGE) would surface uppercase in the generated
        /// multiple-create input type, diverging from the relationship config's authored linking
        /// field names and the other SQL providers. Seed lowercase mappings for every linking column.
        /// </summary>
        protected override void PopulateLinkingEntityExposedNames()
        {
            foreach ((string linkingEntityName, Entity linkingEntity) in _linkingEntities)
            {
                if (!EntityToDatabaseObject.TryGetValue(linkingEntityName, out DatabaseObject? databaseObject))
                {
                    continue;
                }

                Dictionary<string, string> mappings = new(StringComparer.OrdinalIgnoreCase);
                foreach (string columnName in databaseObject.SourceDefinition.Columns.Keys)
                {
                    mappings[columnName] = columnName.ToLowerInvariant();
                }

                _linkingEntities[linkingEntityName] = linkingEntity with { Mappings = mappings };
            }
        }

        /// <summary>
        /// Creates linking-entity metadata for M:N relationships when multiple create is enabled.
        /// Providers that support multiple create override the base no-op.
        /// </summary>
        protected override void PopulateMetadataForLinkingObject(
            string entityName,
            string targetEntityName,
            string linkingObject,
            Dictionary<string, DatabaseObject> sourceObjects)
        {
            if (!_runtimeConfigProvider.GetConfig().IsMultipleCreateOperationEnabled())
            {
                return;
            }

            string linkingEntityName = GraphQLUtils.GenerateLinkingEntityName(entityName, targetEntityName);

            // Linking entities stay off REST/GraphQL endpoints. Schema generation still builds
            // directional linking object types from this metadata when multiple create is enabled.
            Entity linkingEntity = new(
                Source: new EntitySource(Type: EntitySourceType.Table, Object: linkingObject, Parameters: null, KeyFields: null),
                Fields: null,
                Rest: new(Array.Empty<SupportedHttpVerb>(), Enabled: false),
                GraphQL: new(Singular: linkingEntityName, Plural: linkingEntityName, Enabled: false),
                Permissions: Array.Empty<EntityPermission>(),
                Relationships: null,
                Mappings: new(),
                IsLinkingEntity: true);
            _linkingEntities.TryAdd(linkingEntityName, linkingEntity);
            PopulateDatabaseObjectForEntity(linkingEntity, linkingEntityName, sourceObjects);
        }

        /// <summary>
        /// Discovers tables for the configured autoentity patterns and materializes them as
        /// entities, using the Oracle-specific discovery query.
        /// </summary>
        protected override Task GenerateAutoentitiesIntoEntities(IReadOnlyDictionary<string, Autoentity>? autoentities)
        {
            return GenerateAutoentitiesIntoEntities(autoentities, CancellationToken.None);
        }

        /// <inheritdoc/>
        protected override async Task GenerateAutoentitiesIntoEntities(
            IReadOnlyDictionary<string, Autoentity>? autoentities,
            CancellationToken cancellationToken)
        {
            if (autoentities is null)
            {
                return;
            }

            RuntimeConfig runtimeConfig = _runtimeConfigProvider.GetConfig();
            Dictionary<string, Entity> entities = new();
            Dictionary<string, string> entityNameToRawEntity = new();
            foreach ((string autoentityName, Autoentity autoentity) in autoentities)
            {
                cancellationToken.ThrowIfCancellationRequested();
                int addedEntities = 0;
                JsonArray? resultArray = await QueryAutoentitiesFromDatabaseAsync(
                    autoentityName,
                    autoentity,
                    cancellationToken);
                if (resultArray is null)
                {
                    continue;
                }

                foreach (JsonObject? resultObject in resultArray)
                {
                    if (resultObject is null)
                    {
                        throw new DataApiBuilderException(
                            message: $"Cannot create new entity from autoentities definition '{autoentityName}' due to an internal error.",
                            statusCode: HttpStatusCode.InternalServerError,
                            subStatusCode: DataApiBuilderException.SubStatusCodes.ErrorInInitialization);
                    }

                    // Extract the entity name, schema, and database object name from the query result.
                    // The SQL query returns these values with placeholders already replaced.
                    string? entityName = resultObject["entity_name"]?.ToString();
                    string? objectName = resultObject["object"]?.ToString();
                    string? schemaName = resultObject["schema"]?.ToString();

                    if (string.IsNullOrWhiteSpace(entityName) || string.IsNullOrWhiteSpace(objectName) || string.IsNullOrWhiteSpace(schemaName))
                    {
                        _logger.LogError("Skipping autoentity generation: 'entity_name', 'object', or 'schema' is null or empty for autoentities definition '{autoentityName}'.", autoentityName);
                        continue;
                    }

                    // Remove whitespace from the entity name and camelCase-join words so the result is
                    // a valid identifier for REST paths and GraphQL singular/plural names.
                    string rawEntityName = entityName;
                    entityName = RemoveWhitespaceAddCamelCase(entityName);

                    if (string.IsNullOrEmpty(entityName))
                    {
                        _logger.LogError(
                            "Skipping autoentity generation: entity name '{rawEntityName}' for schema '{schemaName}' resolves to an empty string after whitespace removal for autoentities definition '{autoentityName}'.",
                            rawEntityName, schemaName, autoentityName);
                        continue;
                    }

                    if (rawEntityName != entityName)
                    {
                        _logger.LogDebug(
                            "Entity name '{rawEntityName}' was normalized to '{entityName}' by removing whitespace.",
                            rawEntityName, entityName);
                    }

                    // Create the entity using the template settings and permissions from the autoentity configuration.
                    // Currently the source type is always Table for auto-generated entities from database objects.
                    Entity generatedEntity = new(
                        Source: new EntitySource(
                            Object: $"{schemaName}.{objectName}",
                            Type: EntitySourceType.Table,
                            Parameters: null,
                            KeyFields: null),
                        GraphQL: autoentity.Template.GraphQL,
                        Rest: autoentity.Template.Rest,
                        Mcp: autoentity.Template.Mcp,
                        Permissions: ClonePermissions(autoentity.Permissions),
                        Cache: autoentity.Template.Cache,
                        Health: autoentity.Template.Health,
                        Fields: null,
                        Relationships: null,
                        Mappings: new(),
                        IsAutoentity: true);

                    // Add the generated entity to the linking entities dictionary.
                    // This allows the entity to be processed later during metadata population.
                    // A collision can occur when two database objects produce the same entity name after
                    // whitespace removal (e.g. "Order Item" and "OrderItem" both yield "OrderItem").
                    if (!entities.TryAdd(entityName, generatedEntity) || !runtimeConfig.TryAddGeneratedAutoentityNameToDataSourceName(entityName, autoentityName))
                    {
                        string checkEntityName = entityNameToRawEntity.ContainsKey(entityName) && !rawEntityName.Contains(" ")
                            ? entityNameToRawEntity[entityName]
                            : rawEntityName;
                        string collisionMessage = checkEntityName.Contains(" ")
                            ? $"Entity '{entityName}' normalized from '{checkEntityName}' from '{schemaName}' schema conflicts in autoentity pattern '{autoentityName}'. Use --patterns.exclude to skip it."
                            : $"Entity '{entityName}' conflicts in autoentity pattern '{autoentityName}'. Use --patterns.exclude to skip it.";
                        throw new DataApiBuilderException(
                            message: collisionMessage,
                            statusCode: HttpStatusCode.BadRequest,
                            subStatusCode: DataApiBuilderException.SubStatusCodes.ErrorInInitialization);
                    }

                    addedEntities++;
                    entityNameToRawEntity.Add(entityName, rawEntityName);
                }

                if (addedEntities == 0)
                {
                    _logger.LogWarning("No new entities were generated from the autoentities definition '{autoentityName}'.", autoentityName);
                }

                // Track resolution count for validation.
                runtimeConfig.AutoentityResolutionCounts[autoentityName] = addedEntities;
            }

            LogRestPathsForEntities(runtimeConfig, entities);
            _runtimeConfigProvider.AddMergedEntitiesToConfig(entities);
        }

        /// <summary>
        /// Queries the database for autoentities with cooperative cancellation using the
        /// Oracle-specific discovery query.
        /// </summary>
        private async Task<JsonArray?> QueryAutoentitiesFromDatabaseAsync(
            string autoentityName,
            Autoentity autoentity,
            CancellationToken cancellationToken)
        {
            string include = string.Join(",", autoentity.Patterns.Include);
            string exclude = string.Join(",", autoentity.Patterns.Exclude);
            string namePattern = autoentity.Patterns.Name;
            string getAutoentitiesQuery = SqlQueryBuilder.BuildGetAutoentitiesQuery();
            Dictionary<string, DbConnectionParam> parameters = new()
            {
                { $"{BaseQueryStructure.PARAM_NAME_PREFIX}include_pattern", new(include, DbType.String) },
                { $"{BaseQueryStructure.PARAM_NAME_PREFIX}exclude_pattern", new(exclude, DbType.String) },
                { $"{BaseQueryStructure.PARAM_NAME_PREFIX}name_pattern", new(namePattern, DbType.String) }
            };

            _logger.LogDebug("Query for autoentities is being executed with the following parameters.");
            _logger.LogDebug("The autoentities definition '{autoentityName}' include pattern: {include}", autoentityName, include);
            _logger.LogDebug("The autoentities definition '{autoentityName}' exclude pattern: {exclude}", autoentityName, exclude);
            _logger.LogDebug("The autoentities definition '{autoentityName}' name pattern: {namePattern}", autoentityName, namePattern);

            return await QueryExecutor.ExecuteQueryAsync(
                sqltext: getAutoentitiesQuery,
                parameters: parameters,
                dataReaderHandler: QueryExecutor.GetJsonArrayAsync,
                dataSourceName: _dataSourceName,
                cancellationToken: cancellationToken);
        }

        /// <summary>
        /// Oracle column metadata comes from ALL_TAB_COLUMNS, not GetSchema("Columns").
        /// The schema collection is not covered by <see cref="CreateMetadataCommand"/>, so a hung
        /// catalog call would ignore command-timeout. ALL_TAB_COLUMNS also exposes DATA_PRECISION
        /// and DATA_SCALE under stable names and includes DATA_DEFAULT (an Oracle LONG).
        /// Views are listed in ALL_TAB_COLUMNS. Trigger identity is loaded here for tables staged
        /// by <see cref="PopulateTriggerMetadataForTable"/>.
        /// </summary>
        protected override async Task<DataTable> GetColumnsAsync(
            string schemaName,
            string tableName,
            CancellationToken cancellationToken)
        {
            using OracleConnection conn = new();
            conn.ConnectionString = ConnectionString;
            await QueryExecutor.SetManagedIdentityAccessTokenIfAnyAsync(conn, _dataSourceName, cancellationToken);
            await conn.OpenAsync(cancellationToken);

            string owner = string.IsNullOrEmpty(schemaName) ? GetDefaultSchemaName() : schemaName.ToUpperInvariant();
            string table = tableName.ToUpperInvariant();
            DataTable columns = CreateColumnCatalogTable();

            try
            {
                using OracleCommand command = CreateMetadataCommand(
                    conn,
                    "SELECT COLUMN_NAME, DATA_TYPE, DATA_DEFAULT, DATA_PRECISION, DATA_SCALE, DATA_LENGTH " +
                    "FROM ALL_TAB_COLUMNS " +
                    "WHERE OWNER = :owner AND TABLE_NAME = :table_name " +
                    "ORDER BY COLUMN_ID");
                // DATA_DEFAULT is an Oracle LONG. ODP.NET returns an empty string unless this is set.
                command.InitialLONGFetchSize = -1;
                command.Parameters.Add(new OracleParameter("owner", owner));
                command.Parameters.Add(new OracleParameter("table_name", table));

                using OracleDataReader reader = await command.ExecuteReaderAsync(cancellationToken);
                while (await reader.ReadAsync(cancellationToken))
                {
                    DataRow row = columns.NewRow();
                    row["COLUMN_NAME"] = reader.GetString(0);
                    row["DATA_TYPE"] = reader.IsDBNull(1) ? DBNull.Value : reader.GetString(1);
                    string? dataDefault = reader.IsDBNull(2) ? null : Convert.ToString(reader.GetValue(2));
                    row["DATA_DEFAULT"] = string.IsNullOrEmpty(dataDefault) ? DBNull.Value : dataDefault;
                    row["DATA_PRECISION"] = reader.IsDBNull(3) ? DBNull.Value : NormalizeOracleNumber(reader.GetValue(3));
                    row["DATA_SCALE"] = reader.IsDBNull(4) ? DBNull.Value : NormalizeOracleNumber(reader.GetValue(4));
                    row["DATA_LENGTH"] = reader.IsDBNull(5) ? DBNull.Value : NormalizeOracleNumber(reader.GetValue(5));
                    columns.Rows.Add(row);
                }
            }
            catch (OperationCanceledException)
            {
                throw;
            }
            catch (OracleException ex) when (ex.Number == 1013)
            {
                throw MetadataTimeoutException($"reading columns for {owner}.{table}", ex);
            }

            await LoadTriggerIdentityAsync(conn, owner, table, cancellationToken);
            return columns;
        }

        private static DataTable CreateColumnCatalogTable()
        {
            DataTable columns = new();
            columns.Columns.Add("COLUMN_NAME", typeof(string));
            columns.Columns.Add("DATA_TYPE", typeof(string));
            columns.Columns.Add("DATA_DEFAULT", typeof(string));
            columns.Columns.Add("DATA_PRECISION", typeof(object));
            columns.Columns.Add("DATA_SCALE", typeof(object));
            columns.Columns.Add("DATA_LENGTH", typeof(object));
            return columns;
        }

        /// <summary>
        /// ODP.NET may return a catalog NUMBER as <see cref="OracleDecimal"/>. Normalize to
        /// <see cref="decimal"/> so <see cref="Convert.ToInt32(object)"/> can read precision and scale.
        /// </summary>
        private static object NormalizeOracleNumber(object value)
        {
            if (value is OracleDecimal oracleDecimal)
            {
                return oracleDecimal.IsNull ? DBNull.Value : oracleDecimal.Value;
            }

            return value;
        }

        /// <summary>
        /// Oracle-specific implementation to populate column definition with HasDefault and DbType.
        /// Column facts come from ALL_TAB_COLUMNS (DATA_DEFAULT, DATA_TYPE, DATA_PRECISION,
        /// DATA_SCALE, DATA_LENGTH). PRECISION/SCALE and LENGTH remain accepted spellings so a
        /// unit-test DataTable can use either name.
        ///
        /// RAW/BLOB columns are also refined here: ODP.NET's FillSchema/GetSchemaTable path reports
        /// them as System.String (hex-encoded) with ProviderType=DBNull, but DAB's REST/GraphQL
        /// contract treats byte columns as byte[] (base64-serialized via HotChocolate's ByteArray
        /// scalar). Setting SystemType to byte[] here makes the Oracle query builder emit its
        /// base64 conversion (UTL_ENCODE.BASE64_ENCODE) so values round-trip like varbinary on MsSql.
        /// </summary>
        protected override void PopulateColumnDefinitionWithHasDefaultAndDbType(
            SourceDefinition sourceDefinition,
            DataTable allColumnsInTable)
        {
            foreach (DataRow columnInfo in allColumnsInTable.Rows)
            {
                // Keys on sourceDefinition.Columns are the catalog spelling (pass-through
                // GetPhysicalDatabaseColumnName). Match that spelling here.
                string columnName = GetPhysicalDatabaseColumnName((string)columnInfo["COLUMN_NAME"]);

                if (sourceDefinition.Columns.TryGetValue(columnName, out ColumnDefinition? columnDefinition))
                {
                    bool hasDefault =
                        allColumnsInTable.Columns.Contains("DATA_DEFAULT")
                        && columnInfo["DATA_DEFAULT"] is not DBNull
                        && !string.IsNullOrEmpty(columnInfo["DATA_DEFAULT"] as string);

                    columnDefinition.HasDefault = hasDefault;

                    if (hasDefault)
                    {
                        columnDefinition.DefaultValue = columnInfo["DATA_DEFAULT"];
                    }

                    // Refine RAW/BLOB to byte[] (base64 contract). ODP.NET's Columns schema reports the
                    // physical type either as "DATA_TYPE" (some drivers) or "DATATYPE" (ODP.NET
                    // managed), with values "RAW"/"BLOB" - compare ordinal-insensitively and
                    // handle both column spellings so detection does not depend on driver version.
                    string? physicalType = null;
                    if (allColumnsInTable.Columns.Contains("DATA_TYPE"))
                    {
                        physicalType = columnInfo["DATA_TYPE"] as string;
                    }
                    else if (allColumnsInTable.Columns.Contains("DATATYPE"))
                    {
                        physicalType = columnInfo["DATATYPE"] as string;
                    }

                    if (physicalType is not null
                        && (physicalType.Equals("RAW", StringComparison.OrdinalIgnoreCase)
                            || physicalType.Equals("BLOB", StringComparison.OrdinalIgnoreCase)
                            || physicalType.Equals("LONG RAW", StringComparison.OrdinalIgnoreCase)))
                    {
                        columnDefinition.SystemType = typeof(byte[]);
                        columnDefinition.DbType = DbType.Binary;
                        // RAW is a bounded binary type. BLOB and LONG RAW need a LOB output bind.
                        OracleObjectFacts.Column(columnDefinition).IsBlob = !physicalType.Equals("RAW", StringComparison.OrdinalIgnoreCase);
                        if (!OracleObjectFacts.Column(columnDefinition).IsBlob)
                        {
                            columnDefinition.Length = TryReadOracleColumnLength(columnInfo, allColumnsInTable);
                        }

                        continue;
                    }

                    // CLOB/NCLOB columns are surfaced as System.String by the driver, but their
                    // bind/output types must not be limited to VARCHAR2(4000) - the Oracle query
                    // builder maps these to OracleDbType.Clob so RETURNING ... INTO binds hold
                    // values larger than 4000 characters.
                    if (physicalType is not null
                        && (physicalType.Equals("CLOB", StringComparison.OrdinalIgnoreCase)
                            || physicalType.Equals("NCLOB", StringComparison.OrdinalIgnoreCase)))
                    {
                        OracleObjectFacts.Column(columnDefinition).IsClob = true;
                    }

                    // Precision-aware NUMBER mapping. Unconstrained NUMBER (no catalog precision)
                    // stays decimal, preserving the historical mapping; NUMBER(p, 0) narrows to
                    // int (p <= 9) or long (10 <= p <= 18), and NUMBER(p, s) with s > 0 stays
                    // decimal. This is Oracle-only: it never affects the shared SqlToCLRType path.
                    if (physicalType is not null
                        && physicalType.Equals("NUMBER", StringComparison.OrdinalIgnoreCase))
                    {
                        (object? precision, object? scale) = ReadNumberPrecisionAndScale(columnInfo, allColumnsInTable);
                        columnDefinition.SystemType = MapNumberColumnType(precision, scale);
                    }

                    // Bounded string columns expose their maximum length so the query builder can
                    // choose between VARCHAR2 and CLOB for generated JSON output. CLOB/NCLOB (and
                    // LONG) are unbounded and stay on the LOB path.
                    if (columnDefinition.SystemType == typeof(string)
                        && !OracleObjectFacts.Column(columnDefinition).IsClob
                        && physicalType is not null
                        && !physicalType.Equals("LONG", StringComparison.OrdinalIgnoreCase))
                    {
                        columnDefinition.Length = TryReadOracleColumnLength(columnInfo, allColumnsInTable);
                    }

                    columnDefinition.DbType = TypeHelper.GetDbTypeFromSystemType(columnDefinition.SystemType);
                }
            }

            // Apply trigger identity loaded with the column catalog. ODP.NET FillSchema reports
            // IsAutoIncrement=false for sequence triggers, so the cache is the source of truth.
            ApplyTriggerIdentityColumns(sourceDefinition);
        }

        /// <summary>
        /// Preserve the physical column name exactly as Oracle reports it (uppercase for unquoted
        /// identifiers, exact case for quoted ones). The backing column name stored on
        /// <see cref="SourceDefinition.Columns"/> and <see cref="SourceDefinition.PrimaryKey"/> is
        /// emitted verbatim by <see cref="OracleQueryBuilder"/>, so preserving casing lets quoted
        /// lowercase/mixed-case columns resolve correctly. The exposed REST/GraphQL name is the
        /// catalog spelling unless the entity config supplies a mapping or field alias; it is never
        /// lowercased.
        /// </summary>
        protected override string GetPhysicalDatabaseColumnName(string columnName)
        {
            return columnName;
        }

        /// <summary>
        /// Config-authored relationship fields (source.fields / linking fields) commonly use a
        /// different casing than the catalog. Join predicates quote those names, so they must be
        /// rewritten to the physical spelling stored on <see cref="SourceDefinition.Columns"/>.
        /// </summary>
        protected override void NormalizeForeignKeyColumnNames(ForeignKeyDefinition fkDefinition)
        {
            SourceDefinition? referencingDefinition = TryGetSourceDefinitionForDatabaseObject(fkDefinition.Pair.ReferencingDbTable);
            SourceDefinition? referencedDefinition = TryGetSourceDefinitionForDatabaseObject(fkDefinition.Pair.ReferencedDbTable);

            if (referencingDefinition is not null)
            {
                fkDefinition.ReferencingColumns =
                    [.. fkDefinition.ReferencingColumns.Select(column => ResolvePhysicalColumnName(referencingDefinition, column))];
            }

            if (referencedDefinition is not null)
            {
                fkDefinition.ReferencedColumns =
                    [.. fkDefinition.ReferencedColumns.Select(column => ResolvePhysicalColumnName(referencedDefinition, column))];
            }
        }

        /// <summary>
        /// The FK pair may hold a distinct <see cref="DatabaseTable"/> instance from the one stored
        /// in EntityToDatabaseObject (especially linking tables). Match by schema/name when the
        /// pair's own TableDefinition is empty.
        /// </summary>
        private SourceDefinition? TryGetSourceDefinitionForDatabaseObject(DatabaseObject dbObject)
        {
            if (dbObject is DatabaseTable table
                && table.TableDefinition is not null
                && table.TableDefinition.Columns.Count > 0)
            {
                return table.TableDefinition;
            }

            foreach (DatabaseObject entityObject in EntityToDatabaseObject.Values)
            {
                if (entityObject.Equals(dbObject)
                    && entityObject is DatabaseTable entityTable
                    && entityTable.TableDefinition is not null
                    && entityTable.TableDefinition.Columns.Count > 0)
                {
                    return entityTable.TableDefinition;
                }
            }

            return null;
        }

        /// <summary>
        /// ODP.NET reports Oracle RAW/BLOB columns as hex-encoded System.String in the schema table,
        /// but DAB's REST/GraphQL contract treats byte columns as byte[] (base64-serialized via
        /// HotChocolate's ByteArray scalar). Refine those columns to typeof(byte[]) so the Oracle
        /// query builder applies its base64 conversion (UTL_ENCODE.BASE64_ENCODE) and the exposed
        /// values round-trip like varbinary on MsSql.
        /// ProviderType values: 126 = RAW, 113 = BLOB.
        /// NB: the DAB base metadata path (FillSchema + DataTableReader) reports ProviderType as
        /// DBNull, so this is a safety net for paths that surface the int; the authoritative
        /// RAW/BLOB detection for DAB runs in PopulateColumnDefinitionWithHasDefaultAndDbType
        /// via the ODP.NET Columns DATATYPE column.
        /// </summary>
        protected override Type GetSystemTypeFromSchemaTable(DataRow columnInfoFromAdapter, Type driverType)
        {
            if (columnInfoFromAdapter.Table.Columns.Contains("ProviderType")
                && columnInfoFromAdapter["ProviderType"] is int providerType
                && (providerType == 126 || providerType == 113))
            {
                return typeof(byte[]);
            }

            return base.GetSystemTypeFromSchemaTable(columnInfoFromAdapter, driverType);
        }

        /// <summary>
        /// Oracle stores unquoted identifiers in UPPERCASE, so the schema bind for the read-only
        /// (virtual column) query must be uppercased regardless of the casing authored in the
        /// config source, matching the FK and column-metadata lookups.
        /// </summary>
        protected override string GetSchemaOrDatabaseNameForReadOnlyColumnQuery(string schemaOrDatabaseName)
        {
            return schemaOrDatabaseName.ToUpperInvariant();
        }

        /// <summary>
        /// Oracle-specific implementation to populate stored procedure schema information.
        /// Oracle only supports 2 restrictions (Owner, Name) for the Procedures collection,
        /// unlike SQL Server which supports 4 (Database, Schema, Table, Column).
        /// For a subprogram inside a package (source "schema.package.subprogram"), the underlying
        /// <see cref="OracleObjectFacts"/> holds the package name and whether the subprogram
        /// is a function. ODP.NET schema collections have no direct representation for those,
        /// so they are resolved against ALL_ARGUMENTS/ALL_PROCEDURES below.
        /// </summary>
        protected override async Task FillSchemaForStoredProcedureAsync(
            Azure.DataApiBuilder.Config.ObjectModel.Entity procedureEntity,
            string entityName,
            string schemaName,
            string storedProcedureSourceName,
            StoredProcedureDefinition storedProcedureDefinition,
            CancellationToken cancellationToken)
        {
            // Package name and function-ness were parsed from the config source onto
            // OracleObjectFacts during PopulateDatabaseObjectForEntity.
            DatabaseStoredProcedure dbSp = (DatabaseStoredProcedure)EntityToDatabaseObject[entityName];

            using OracleConnection conn = new();
            conn.ConnectionString = ConnectionString;
            await QueryExecutor.SetManagedIdentityAccessTokenIfAnyAsync(conn, _dataSourceName, cancellationToken);
            await conn.OpenAsync(cancellationToken);

            string schemaFilter = string.IsNullOrEmpty(schemaName) ? GetDefaultSchemaName() : schemaName.ToUpperInvariant();
            string objectFilter = storedProcedureSourceName.ToUpperInvariant();

            // ALL_ARGUMENTS keys a standalone subprogram by (OWNER, OBJECT_NAME) with PACKAGE_NAME IS
            // NULL, and a packaged subprogram by (OWNER, PACKAGE_NAME, OBJECT_NAME). A function
            // additionally exposes its RETURN value as a POSITION 0 row with a NULL ARGUMENT_NAME.
            string packageClause = OracleObjectFacts.Procedure(dbSp).PackageName is null
                ? "PACKAGE_NAME IS NULL"
                : "PACKAGE_NAME = :package_name";
            // DATA_LEVEL 0 is the subprogram signature. Nested record fields are DATA_LEVEL > 0
            // and are not part of the call the client configures.
            string argumentsQuery =
                "SELECT ARGUMENT_NAME, DATA_TYPE, IN_OUT, POSITION, OVERLOAD, DEFAULTED " +
                "FROM ALL_ARGUMENTS " +
                "WHERE OWNER = :owner " +
                "AND OBJECT_NAME = :object_name " +
                $"AND {packageClause} " +
                "AND DATA_LEVEL = 0 " +
                "ORDER BY OVERLOAD, POSITION";

            bool isFunction = false;
            List<OracleArgumentRow> argumentRows = new();
            try
            {
                using OracleCommand command = CreateMetadataCommand(conn, argumentsQuery);
                command.Parameters.Add(new OracleParameter("owner", schemaFilter));
                command.Parameters.Add(new OracleParameter("object_name", objectFilter));
                if (OracleObjectFacts.Procedure(dbSp).PackageName is string packageName)
                {
                    command.Parameters.Add(new OracleParameter("package_name", packageName.ToUpperInvariant()));
                }

                using OracleDataReader reader = await command.ExecuteReaderAsync(cancellationToken);
                while (await reader.ReadAsync(cancellationToken))
                {
                    argumentRows.Add(new OracleArgumentRow(
                        Name: reader.IsDBNull(0) ? null : reader.GetString(0),
                        DataType: reader.IsDBNull(1) ? string.Empty : reader.GetString(1),
                        InOut: reader.IsDBNull(2) ? "IN" : reader.GetString(2),
                        Position: Convert.ToInt32(NormalizeOracleNumber(reader.GetValue(3))),
                        Overload: reader.IsDBNull(4) ? null : reader.GetString(4),
                        Defaulted: reader.IsDBNull(5) ? null : reader.GetString(5)));
                }
            }
            catch (OperationCanceledException)
            {
                throw;
            }
            catch (OracleException ex) when (ex.Number == 1013)
            {
                throw MetadataTimeoutException($"reading arguments for {schemaFilter}.{objectFilter}", ex);
            }

            if (argumentRows.Count > 0)
            {
                IEnumerable<string>? configuredNames = procedureEntity.Source.Parameters?.Select(parameter => parameter.Name);
                string? packageForName = OracleObjectFacts.Procedure(dbSp).PackageName;
                string qualifiedName = string.IsNullOrEmpty(packageForName)
                    ? $"{schemaFilter}.{objectFilter}"
                    : $"{schemaFilter}.{packageForName}.{objectFilter}";
                // #n stored while parsing the source selects metadata even when names do not match.
                // After selection, keep the catalog OVERLOAD spelling (so #02 binds as 2).
                string? configuredOverload = OracleObjectFacts.Procedure(dbSp).Overload;
                List<OracleArgumentRow> selected;
                try
                {
                    selected = SelectOracleOverload(argumentRows, configuredNames, configuredOverload, qualifiedName);
                }
                catch (DataApiBuilderException exception)
                {
                    if (_isValidateOnly)
                    {
                        SqlMetadataExceptions.Add(exception);
                        return;
                    }

                    throw;
                }

                OracleObjectFacts.Procedure(dbSp).Overload = selected.Count > 0 ? selected[0].Overload : null;

                foreach (OracleArgumentRow row in selected.OrderBy(argument => argument.Position))
                {
                    if (row.Position == 0)
                    {
                        // POSITION 0 is a function's RETURN value, not an input argument.
                        isFunction = true;
                        continue;
                    }

                    if (string.IsNullOrEmpty(row.Name))
                    {
                        continue;
                    }

                    Type systemType = SqlToCLRType(row.DataType);
                    // REF CURSOR is the result path (bound as :dab_result), not a client input.
                    // Pure OUT scalars are not bound as IN parameters.
                    if (systemType == typeof(IDataReader) ||
                        row.InOut.Equals("OUT", StringComparison.OrdinalIgnoreCase))
                    {
                        continue;
                    }

                    storedProcedureDefinition.Parameters.TryAdd(
                        row.Name.TrimStart('@', ':'),
                        new ParameterDefinition
                        {
                            SystemType = systemType,
                            DbType = TypeHelper.GetDbTypeFromSystemType(systemType)
                        });
                }
            }
            else if (!await OracleSubprogramExistsAsync(conn, schemaFilter, dbSp, objectFilter, cancellationToken))
                {
                    // No ALL_ARGUMENTS rows: either a parameterless subprogram (valid) or a
                    // non-existent object (error). Distinguish via ALL_PROCEDURES.
                    var notFoundException = new DataApiBuilderException(
                        message: $"No stored procedure definition found for the given database object {schemaFilter}.{objectFilter}",
                        statusCode: System.Net.HttpStatusCode.ServiceUnavailable,
                        subStatusCode: DataApiBuilderException.SubStatusCodes.ErrorInInitialization);

                    if (_isValidateOnly)
                    {
                        SqlMetadataExceptions.Add(notFoundException);
                        return;
                    }
                    else
                    {
                        throw notFoundException;
                    }
            }

            OracleObjectFacts.Procedure(dbSp).IsFunction = isFunction;

            // Loop through parameters specified in config, throw error if not found in schema
            // else set runtime config defined default values.
            // Note: we defer type checking of parameters specified in config until request time
            List<ParameterMetadata>? configParameters = procedureEntity.Source.Parameters;
            if (configParameters is not null)
            {
                foreach (ParameterMetadata paramMeta in configParameters)
                {
                    // ALL_ARGUMENTS stores unquoted names in uppercase. Match once here.
                    // The exposed key becomes the configured spelling so REST and GraphQL
                    // stay ordinal-exact. The catalog name is stored beside the entry and
                    // is what the quoted PL/SQL association emits.
                    string? catalogKey = null;
                    foreach (string key in storedProcedureDefinition.Parameters.Keys)
                    {
                        if (string.Equals(key, paramMeta.Name, StringComparison.OrdinalIgnoreCase))
                        {
                            catalogKey = key;
                            break;
                        }
                    }

                    if (catalogKey is null)
                    {
                        var exception = new DataApiBuilderException(
                            message: $"Could not find parameter \"{paramMeta.Name}\" specified in config for procedure \"{schemaName}.{storedProcedureSourceName}\"",
                            statusCode: System.Net.HttpStatusCode.ServiceUnavailable,
                            subStatusCode: DataApiBuilderException.SubStatusCodes.ErrorInInitialization);

                        if (_isValidateOnly)
                        {
                            SqlMetadataExceptions.Add(exception);
                        }
                        else
                        {
                            throw exception;
                        }
                    }
                    else
                    {
                        ParameterDefinition parameterDefinition = storedProcedureDefinition.Parameters[catalogKey];
                        OracleObjectFacts.Argument(parameterDefinition).CatalogName = catalogKey;
                        if (!string.Equals(catalogKey, paramMeta.Name, StringComparison.Ordinal))
                        {
                            storedProcedureDefinition.Parameters.Remove(catalogKey);
                            storedProcedureDefinition.Parameters.Add(paramMeta.Name, parameterDefinition);
                        }

                        // Map all metadata from config
                        parameterDefinition.Description = paramMeta.Description;
                        parameterDefinition.Required = paramMeta.Required;
                        parameterDefinition.Default = paramMeta.Default;
                        parameterDefinition.HasConfigDefault = paramMeta.Default is not null;
                        parameterDefinition.ConfigDefaultValue = paramMeta.Default?.ToString();
                    }
                }
            }

            // Generating exposed stored-procedure query/mutation name and adding to the dictionary mapping it to its entity name.
            GraphQLStoredProcedureExposedNameToEntityNameMap.TryAdd(GenerateStoredProcedureGraphQLFieldName(entityName, procedureEntity), entityName);
        }

        /// <summary>
        /// Confirms the configured Oracle subprogram exists when ALL_ARGUMENTS returned no rows
        /// (a parameterless subprogram has no argument metadata). Standalone subprograms are keyed by
        /// OBJECT_NAME with a NULL PROCEDURE_NAME; packaged subprograms are keyed by OBJECT_NAME =
        /// package name and PROCEDURE_NAME = subprogram name.
        /// </summary>
        private async Task<bool> OracleSubprogramExistsAsync(
            OracleConnection conn,
            string schema,
            DatabaseStoredProcedure dbSp,
            string objectFilter,
            CancellationToken cancellationToken)
        {
            string query = OracleObjectFacts.Procedure(dbSp).PackageName is null
                ? "SELECT 1 FROM ALL_PROCEDURES " +
                  "WHERE OWNER = :owner AND OBJECT_NAME = :object_name " +
                  "AND PROCEDURE_NAME IS NULL AND OBJECT_TYPE IN ('PROCEDURE', 'FUNCTION') " +
                  "FETCH FIRST 1 ROWS ONLY"
                : "SELECT 1 FROM ALL_PROCEDURES " +
                  "WHERE OWNER = :owner AND OBJECT_NAME = :package_name AND PROCEDURE_NAME = :object_name " +
                  "FETCH FIRST 1 ROWS ONLY";

            using OracleCommand command = CreateMetadataCommand(conn, query);
            command.Parameters.Add(new OracleParameter("owner", schema));
            command.Parameters.Add(new OracleParameter("object_name", objectFilter));
            if (OracleObjectFacts.Procedure(dbSp).PackageName is string packageName)
            {
                command.Parameters.Add(new OracleParameter("package_name", packageName.ToUpperInvariant()));
            }

            try
            {
                using OracleDataReader reader = await command.ExecuteReaderAsync(cancellationToken);
                return await reader.ReadAsync(cancellationToken);
            }
            catch (OperationCanceledException)
            {
                throw;
            }
            catch (OracleException ex) when (ex.Number == 1013)
            {
                throw MetadataTimeoutException($"checking whether {schema}.{objectFilter} exists", ex);
            }
        }

        /// <summary>
        /// Overrides the base stored-procedure result-set discovery to be Oracle package/function
        /// aware. The base implementation builds the ALL_ARGUMENTS query from only the
        /// schema.subprogram name, which is insufficient for a subprogram inside a package (whose
        /// arguments are keyed by PACKAGE_NAME plus the bare subprogram name) or for a function
        /// (whose result set is its RETURN value at POSITION 0). For those, the package-aware
        /// OracleQueryBuilder query is used so the result set definition is populated correctly.
        /// </summary>
        protected override async Task PopulateResultSetDefinitionsForStoredProcedureAsync(
            string schemaName,
            string storedProcedureName,
            SourceDefinition sourceDefinition,
            string entityName,
            CancellationToken cancellationToken)
        {
            StoredProcedureDefinition storedProcedureDefinition = (StoredProcedureDefinition)sourceDefinition;
            DatabaseStoredProcedure dbSp = (DatabaseStoredProcedure)EntityToDatabaseObject[entityName];

            // One query shape for standalone and packaged subprograms so OVERLOAD is applied
            // the same way arguments were chosen in FillSchemaForStoredProcedureAsync.
            string resultQuery = ((OracleQueryBuilder)SqlQueryBuilder).BuildStoredProcedureResultDetailsQuery(
                schemaName: schemaName,
                packageName: OracleObjectFacts.Procedure(dbSp).PackageName,
                subprogramName: storedProcedureName,
                isFunction: OracleObjectFacts.Procedure(dbSp).IsFunction,
                overload: OracleObjectFacts.Procedure(dbSp).Overload);
            Dictionary<string, DbConnectionParam> resultQueryParameters = new()
            {
                { "@param0", new DbConnectionParam(schemaName, DbType.String) },
                { "@param1", new DbConnectionParam(OracleObjectFacts.Procedure(dbSp).PackageName, DbType.String) },
                { "@param2", new DbConnectionParam(storedProcedureName, DbType.String) },
            };
            if (!string.IsNullOrEmpty(OracleObjectFacts.Procedure(dbSp).Overload))
            {
                resultQueryParameters.Add("@param3", new DbConnectionParam(OracleObjectFacts.Procedure(dbSp).Overload, DbType.String));
            }

            JsonArray? resultArray = await QueryExecutor.ExecuteQueryAsync(
                sqltext: resultQuery,
                parameters: resultQueryParameters,
                dataReaderHandler: QueryExecutor.GetJsonArrayAsync,
                dataSourceName: _dataSourceName,
                cancellationToken: cancellationToken);

            using JsonDocument sqlResult = JsonDocument.Parse(resultArray!.ToJsonString());

            foreach (JsonElement element in sqlResult.RootElement.EnumerateArray())
            {
                if (!TryGetPropertyByCaseInsensitiveName(element, BaseSqlQueryBuilder.STOREDPROC_COLUMN_NAME, out JsonElement nameElement))
                {
                    throw new DataApiBuilderException(
                        message: $"Unexpected stored procedure metadata shape for '{schemaName}.{storedProcedureName}': " +
                                $"missing column '{BaseSqlQueryBuilder.STOREDPROC_COLUMN_NAME}'.",
                        statusCode: System.Net.HttpStatusCode.ServiceUnavailable,
                        subStatusCode: DataApiBuilderException.SubStatusCodes.ErrorInInitialization);
                }

                if (!TryGetPropertyByCaseInsensitiveName(element, BaseSqlQueryBuilder.STOREDPROC_COLUMN_SYSTEMTYPENAME, out JsonElement typeElement))
                {
                    throw new DataApiBuilderException(
                        message: $"Unexpected stored procedure metadata shape for '{schemaName}.{storedProcedureName}': " +
                                $"missing column '{BaseSqlQueryBuilder.STOREDPROC_COLUMN_SYSTEMTYPENAME}'.",
                        statusCode: System.Net.HttpStatusCode.ServiceUnavailable,
                        subStatusCode: DataApiBuilderException.SubStatusCodes.ErrorInInitialization);
                }

                string resultFieldName = nameElement.ToString();
                Type resultFieldType = SqlToCLRType(typeElement.ToString());

                // A function's RETURN value is reported under a NULL ARGUMENT_NAME. Only a function
                // that returns a REF CURSOR declares a result set (captured through the :dab_result
                // bind); a scalar function has no result-set definition and is invoked by
                // OracleQueryBuilder as SELECT ... FROM DUAL, so skip it here.
                if (OracleObjectFacts.Procedure(dbSp).IsFunction && resultFieldType != typeof(IDataReader))
                {
                    continue;
                }

                if (string.IsNullOrWhiteSpace(resultFieldName))
                {
                    // Name a function's cursor result after the subprogram so it is addressable.
                    resultFieldName = OracleObjectFacts.Procedure(dbSp).IsFunction ? storedProcedureName : resultFieldName;
                }

                if (string.IsNullOrWhiteSpace(resultFieldName))
                {
                    throw new DataApiBuilderException(
                        message: $"The stored procedure '{schemaName}.{storedProcedureName}' returns a column without a name. " +
                                "This typically happens when using aggregate functions (like MAX, MIN, COUNT) or expressions " +
                                "without providing an alias. Please add column aliases to your SELECT statement. " +
                                "For example: 'SELECT MAX(id) AS MaxId' instead of 'SELECT MAX(id)'.",
                        statusCode: System.Net.HttpStatusCode.ServiceUnavailable,
                        subStatusCode: DataApiBuilderException.SubStatusCodes.ErrorInInitialization);
                }

                storedProcedureDefinition.Columns.TryAdd(resultFieldName, new(resultFieldType) { IsNullable = true });
            }

            static bool TryGetPropertyByCaseInsensitiveName(JsonElement element, string name, out JsonElement value)
            {
                foreach (JsonProperty property in element.EnumerateObject())
                {
                    if (string.Equals(property.Name, name, StringComparison.OrdinalIgnoreCase))
                    {
                        value = property.Value;
                        return true;
                    }
                }

                value = default;
                return false;
            }
        }

        /// <summary>
        /// Takes a string version of an Oracle data type and returns its .NET common language runtime (CLR) counterpart
        /// As per Oracle documentation for type mappings
        /// </summary>
        public override Type SqlToCLRType(string sqlType)
        {
            return sqlType.ToUpperInvariant() switch
            {
                "BOOLEAN" => typeof(bool),
                "NUMBER" => typeof(decimal),
                "FLOAT" => typeof(double),
                "BINARY_FLOAT" => typeof(float),
                "BINARY_DOUBLE" => typeof(double),
                "VARCHAR2" => typeof(string),
                "NVARCHAR2" => typeof(string),
                "CHAR" => typeof(string),
                "NCHAR" => typeof(string),
                "CLOB" => typeof(string),
                "NCLOB" => typeof(string),
                "DATE" => typeof(DateTime),
                "TIMESTAMP" => typeof(DateTime),
                "TIMESTAMP WITH TIME ZONE" => typeof(DateTimeOffset),
                "TIMESTAMP WITH LOCAL TIME ZONE" => typeof(DateTime),
                "RAW" => typeof(byte[]),
                "BLOB" => typeof(byte[]),
                "LONG" => typeof(string),
                "LONG RAW" => typeof(byte[]),
                "ROWID" => typeof(string),
                "UROWID" => typeof(string),
                "CURSOR" or "REF CURSOR" => typeof(IDataReader),
                _ => typeof(object)
            };
        }

        /// <summary>
        /// Oracle-specific implementation to build foreign key query parameters.
        /// Ensures that schema names and table names are converted to uppercase
        /// as Oracle stores identifiers in uppercase when unquoted.
        /// </summary>
        protected override Dictionary<string, DbConnectionParam> GetForeignKeyQueryParams(
            string[] schemaNames,
            string[] tableNames)
        {
            // Build the parameters dictionary using the base implementation
            Dictionary<string, DbConnectionParam> parameters = new();
            string[] schemaNameParams =
                BaseSqlQueryBuilder.CreateParams(
                    kindOfParam: BaseSqlQueryBuilder.SCHEMA_NAME_PARAM,
                    schemaNames.Count());
            string[] tableNameParams =
                BaseSqlQueryBuilder.CreateParams(
                    kindOfParam: BaseSqlQueryBuilder.TABLE_NAME_PARAM,
                    tableNames.Count());

            // Add schema name parameters with uppercase values
            for (int i = 0; i < schemaNames.Count(); ++i)
            {
                parameters.Add(schemaNameParams[i], new(schemaNames[i].ToUpperInvariant(), DbType.String));
            }

            // Add table name parameters with uppercase values
            for (int i = 0; i < tableNames.Count(); ++i)
            {
                parameters.Add(tableNameParams[i], new(tableNames[i].ToUpperInvariant(), DbType.String));
            }

            return parameters;
        }

        internal readonly record struct OracleArgumentRow(
            string? Name,
            string DataType,
            string InOut,
            int Position,
            string? Overload,
            string? Defaulted = null);

        /// <summary>
        /// Picks one ALL_ARGUMENTS overload. A configured <paramref name="configuredOverload"/>
        /// (<c>#n</c> on the source object) selects that overload's metadata even when the
        /// configured names do not match; the named PL/SQL call is still resolved by Oracle.
        /// A single overload is returned unchanged. Several overloads require the configured
        /// names to equal one overload's input formals (IN and IN/OUT, position &gt; 0). OUT,
        /// REF CURSOR, and the function RETURN row are not input formals. A defaulted formal
        /// is still part of that set: omitting it is not a match. Zero matches or several
        /// matches fail startup. There is no lowest-overload fallback.
        /// </summary>
        internal static List<OracleArgumentRow> SelectOracleOverload(
            IReadOnlyList<OracleArgumentRow> rows,
            IEnumerable<string>? configuredParameterNames,
            string? configuredOverload = null,
            string? qualifiedName = null)
        {
            List<IGrouping<string, OracleArgumentRow>> groups = rows
                .GroupBy(row => row.Overload ?? string.Empty, StringComparer.Ordinal)
                .ToList();
            string target = string.IsNullOrWhiteSpace(qualifiedName) ? "the configured stored procedure" : qualifiedName;

            if (!string.IsNullOrEmpty(configuredOverload))
            {
                IGrouping<string, OracleArgumentRow>? match = groups.FirstOrDefault(group =>
                    OverloadNumbersMatch(group.Key, configuredOverload));
                if (match is null)
                {
                    throw OverloadSelectionException(
                        target,
                        groups,
                        configuredParameterNames,
                        $"No overload matches the configured disambiguator #{configuredOverload}.");
                }

                return match.ToList();
            }

            if (groups.Count <= 1)
            {
                return rows.ToList();
            }

            HashSet<string> configured = ConfiguredNames(configuredParameterNames);
            List<IGrouping<string, OracleArgumentRow>> exact = groups
                .Where(group => InputFormalNames(group).SetEquals(configured))
                .ToList();
            if (exact.Count == 1)
            {
                return exact[0].ToList();
            }

            string reason = exact.Count == 0
                ? "No overload's input parameters exactly match the configured parameter names."
                : "More than one overload's input parameters exactly match the configured parameter names.";
            throw OverloadSelectionException(target, groups, configured, reason);
        }

        private static bool OverloadNumbersMatch(string catalogOverload, string configuredOverload)
        {
            if (string.Equals(catalogOverload, configuredOverload, StringComparison.Ordinal))
            {
                return true;
            }

            return int.TryParse(catalogOverload, out int catalogNumber)
                && int.TryParse(configuredOverload, out int configuredNumber)
                && catalogNumber == configuredNumber;
        }

        private static HashSet<string> ConfiguredNames(IEnumerable<string>? configuredParameterNames)
        {
            HashSet<string> configured = new(StringComparer.OrdinalIgnoreCase);
            if (configuredParameterNames is null)
            {
                return configured;
            }

            foreach (string name in configuredParameterNames)
            {
                if (!string.IsNullOrWhiteSpace(name))
                {
                    configured.Add(name);
                }
            }

            return configured;
        }

        /// <summary>
        /// Input formals are named arguments at position &gt; 0 whose direction is not OUT.
        /// IN/OUT counts. A defaulted argument still counts: DEFAULTED is reported, not used to
        /// treat the formal as optional.
        /// </summary>
        private static HashSet<string> InputFormalNames(IEnumerable<OracleArgumentRow> rows)
        {
            HashSet<string> names = new(StringComparer.OrdinalIgnoreCase);
            foreach (OracleArgumentRow row in rows)
            {
                if (row.Position <= 0 || string.IsNullOrEmpty(row.Name))
                {
                    continue;
                }

                if (row.InOut.Equals("OUT", StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                names.Add(row.Name);
            }

            return names;
        }

        private static DataApiBuilderException OverloadSelectionException(
            string qualifiedName,
            IEnumerable<IGrouping<string, OracleArgumentRow>> groups,
            IEnumerable<string>? configuredParameterNames,
            string reason)
        {
            HashSet<string> configured = ConfiguredNames(configuredParameterNames);
            string configuredText = configured.Count == 0
                ? "(none)"
                : string.Join(", ", configured.OrderBy(name => name, StringComparer.OrdinalIgnoreCase));
            string overloads = string.Join("; ", groups.Select(DescribeOverload));
            return new DataApiBuilderException(
                message: $"Could not choose an Oracle overload for {qualifiedName}. {reason} " +
                         $"Configured parameters: {configuredText}. Overloads: {overloads}. " +
                         "Add #n to the source object (for example schema.package.subprogram#2) to select that overload's metadata. " +
                         "The suffix selects metadata only; Oracle still resolves the named PL/SQL call.",
                statusCode: HttpStatusCode.ServiceUnavailable,
                subStatusCode: DataApiBuilderException.SubStatusCodes.ErrorInInitialization);
        }

        private static string DescribeOverload(IGrouping<string, OracleArgumentRow> group)
        {
            string number = string.IsNullOrEmpty(group.Key) ? "(not overloaded)" : "#" + group.Key;
            List<string> formals = new();
            foreach (OracleArgumentRow row in group.OrderBy(row => row.Position))
            {
                if (row.Position <= 0 || string.IsNullOrEmpty(row.Name))
                {
                    continue;
                }

                string formal = row.Name;
                if (row.InOut.Equals("OUT", StringComparison.OrdinalIgnoreCase))
                {
                    formal += " OUT";
                }
                else if (string.Equals(row.Defaulted, "Y", StringComparison.OrdinalIgnoreCase))
                {
                    formal += " DEFAULT";
                }

                formals.Add(formal);
            }

            string signature = formals.Count == 0 ? "no input parameters" : string.Join(", ", formals);
            return $"{number} ({signature})";
        }

        /// <summary>
        /// Reads NUMBER precision and scale. ALL_TAB_COLUMNS names (DATA_PRECISION, DATA_SCALE)
        /// win when present. PRECISION and SCALE remain fallbacks for older schema-table spellings.
        /// </summary>
        internal static (object? Precision, object? Scale) ReadNumberPrecisionAndScale(DataRow columnInfo, DataTable table)
        {
            return (ReadCatalogNumber(columnInfo, table, "DATA_PRECISION", "PRECISION"),
                ReadCatalogNumber(columnInfo, table, "DATA_SCALE", "SCALE"));
        }

        private static object? ReadCatalogNumber(DataRow row, DataTable table, string primary, string fallback)
        {
            if (TryReadCatalogNumber(row, table, primary, out object? primaryValue))
            {
                return primaryValue;
            }

            if (TryReadCatalogNumber(row, table, fallback, out object? fallbackValue))
            {
                return fallbackValue;
            }

            return null;
        }

        private static bool TryReadCatalogNumber(DataRow row, DataTable table, string columnName, out object? value)
        {
            value = null;
            if (!table.Columns.Contains(columnName) || row[columnName] is DBNull)
            {
                return false;
            }

            object normalized = NormalizeOracleNumber(row[columnName]);
            if (normalized is DBNull)
            {
                return false;
            }

            value = normalized;
            return true;
        }

        /// <summary>
        /// Maps an Oracle NUMBER column to the closest .NET type from its catalog precision and
        /// scale. The canonical source is ALL_TAB_COLUMNS DATA_PRECISION/DATA_SCALE.
        /// PRECISION/SCALE remain fallbacks. Unconstrained NUMBER reports no precision and stays decimal,
        /// preserving the historical "NUMBER -> decimal" behaviour.
        /// <list type="bullet">
        /// <item><c>NUMBER(p, 0)</c> with <c>p &lt;= 9</c> maps to <see cref="int"/>.</item>
        /// <item><c>NUMBER(p, 0)</c> with <c>10 &lt;= p &lt;= 18</c> maps to <see cref="long"/>.</item>
        /// <item><c>NUMBER(p, 0)</c> with <c>p &gt; 18</c> maps to <see cref="decimal"/>.</item>
        /// <item><c>NUMBER(p, s)</c> with <c>s &gt; 0</c> maps to <see cref="decimal"/>.</item>
        /// </list>
        /// </summary>
        /// <param name="precision">The column's DATA_PRECISION (PRECISION), or null/DBNull for an
        /// unconstrained NUMBER.</param>
        /// <param name="scale">The column's DATA_SCALE (SCALE), or null/DBNull when unspecified.</param>
        internal static Type MapNumberColumnType(object? precision, object? scale)
        {
            // Unconstrained NUMBER reports NULL precision/scale from the catalog.
            if (precision is null || precision is DBNull)
            {
                return typeof(decimal);
            }

            int p = Convert.ToInt32(precision);
            int s = scale is null || scale is DBNull ? 0 : Convert.ToInt32(scale);

            // Fractional NUMBER (scale > 0) cannot be represented losslessly in an integral type.
            if (s > 0)
            {
                return typeof(decimal);
            }

            return p switch
            {
                <= 9 => typeof(int),
                <= 18 => typeof(long),
                _ => typeof(decimal)
            };
        }

        private static int? TryReadOracleColumnLength(DataRow columnInfo, DataTable table)
        {
            foreach (string columnName in new[] { "DATA_LENGTH", "LENGTH" })
            {
                if (!table.Columns.Contains(columnName) || columnInfo[columnName] is DBNull)
                {
                    continue;
                }

                if (int.TryParse(columnInfo[columnName]?.ToString(), out int length) && length > 0)
                {
                    return length;
                }
            }

            return null;
        }
