        private static readonly Regex AssignmentAt = new(
            @":new\s*\.\s*(?:""([^""]+)""|([A-Za-z0-9_$#]+))\s*:=\s*(?:(?:""[^""]+""|[A-Za-z0-9_$#]+)\s*\.\s*)+NEXTVAL",
            RegexOptions.IgnoreCase | RegexOptions.Compiled | RegexOptions.CultureInvariant);

        private static readonly Regex SelectIntoAt = new(
            @"SELECT\s+(?:(?:""[^""]+""|[A-Za-z0-9_$#]+)\s*\.\s*)+NEXTVAL\s+INTO\s+:new\s*\.\s*(?:""([^""]+)""|([A-Za-z0-9_$#]+))",
            RegexOptions.IgnoreCase | RegexOptions.Compiled | RegexOptions.CultureInvariant);

        /// <summary>
        /// Reads BEFORE EACH ROW insert triggers for one table into <see cref="_triggerIdentityByTable"/>.
        /// A null <c>TRIGGER_BODY</c> (wrapped trigger) is logged and contributes no identity columns.
        /// A catalog error other than a command timeout is non-fatal. ORA-01013 fails startup.
        /// </summary>
        private async Task LoadTriggerIdentityAsync(
            OracleConnection connection,
            string owner,
            string table,
            CancellationToken cancellationToken)
        {
            if (_triggerTables is null || _triggerIdentityByTable is null || !_triggerTables.Contains((owner, table)))
            {
                return;
            }

            if (_triggerIdentityByTable.ContainsKey((owner, table)))
            {
                return;
            }

            const string triggerQuery =
                "SELECT TRIGGER_NAME, TRIGGERING_EVENT, TRIGGER_TYPE, TRIGGER_BODY FROM ALL_TRIGGERS " +
                "WHERE OWNER = :owner AND TABLE_NAME = :table_name " +
                "AND TRIGGER_TYPE = 'BEFORE EACH ROW' " +
                "AND TRIGGERING_EVENT LIKE '%INSERT%' " +
                "AND STATUS = 'ENABLED'";

            Dictionary<string, bool> identity = new(StringComparer.OrdinalIgnoreCase);
            try
            {
                using OracleCommand command = CreateMetadataCommand(connection, triggerQuery);
                // TRIGGER_BODY is an Oracle LONG. ODP.NET returns an empty string unless this is set.
                command.InitialLONGFetchSize = -1;
                command.Parameters.Add(new OracleParameter("owner", owner));
                command.Parameters.Add(new OracleParameter("table_name", table));

                using OracleDataReader reader = await command.ExecuteReaderAsync(cancellationToken);
                while (await reader.ReadAsync(cancellationToken))
                {
                    string triggerName = reader.IsDBNull(0) ? "(unnamed)" : reader.GetString(0);
                    if (reader.IsDBNull(3))
                    {
                        _logger.LogWarning(
                            "Oracle trigger {Trigger} on {Owner}.{Table} has no TRIGGER_BODY. Wrapped triggers are not parsed, so no identity columns were inferred from it.",
                            triggerName,
                            owner,
                            table);
                        continue;
                    }

                    string? triggeringEvent = reader.IsDBNull(1) ? null : reader.GetString(1);
                    string? triggerType = reader.IsDBNull(2) ? null : reader.GetString(2);
                    MergeTriggerIdentity(
                        identity,
                        ClassifyTrigger(triggerType, triggeringEvent, reader.GetString(3)));
                }
            }
            catch (OperationCanceledException)
            {
                throw;
            }
            catch (OracleException ex) when (ex.Number == 1013)
            {
                throw MetadataTimeoutException($"reading insert triggers for {owner}.{table}", ex);
            }
            catch (Exception ex)
            {
                _logger.LogWarning(
                    ex,
                    "Failed to detect Oracle trigger-based identity columns for {Owner}.{Table}; falling back to driver IsAutoIncrement metadata.",
                    owner,
                    table);
                return;
            }

            _triggerIdentityByTable[(owner, table)] = identity;
        }

        /// <summary>
        /// Applies trigger identity cached by <see cref="LoadTriggerIdentityAsync"/>.
        /// <paramref name="sourceDefinition"/> columns with an unguarded sequence assignment become
        /// read-only. A guard of <c>:new.col IS NULL</c> stays writable (generated by default).
        /// </summary>
        private void ApplyTriggerIdentityColumns(SourceDefinition sourceDefinition)
        {
            if (_sourceTableMap is null || _triggerIdentityByTable is null)
            {
                return;
            }

            if (!_sourceTableMap.TryGetValue(sourceDefinition, out (string SchemaName, string TableName) tableInfo))
            {
                return;
            }

            if (!_triggerIdentityByTable.TryGetValue((tableInfo.SchemaName, tableInfo.TableName), out Dictionary<string, bool>? columns))
            {
                return;
            }

            foreach ((string name, bool isReadOnly) in columns)
            {
                if (!TryGetTriggerColumn(sourceDefinition, name, out ColumnDefinition? columnDefinition) || columnDefinition is null)
                {
                    continue;
                }

                columnDefinition.IsAutoGenerated = true;
                columnDefinition.IsReadOnly = isReadOnly;
            }
        }

        /// <summary>
        /// Matches a trigger column to the catalog spelling. The column dictionary ignores case,
        /// so this walks the keys. A quoted reference (<c>:new."Id"</c>) matches <c>Id</c> only.
        /// An unquoted reference is folded to uppercase, which is the catalog spelling of an
        /// unquoted column, and does not attach to a quoted column of another case.
        /// </summary>
        internal static bool TryGetTriggerColumn(
            SourceDefinition sourceDefinition,
            string columnName,
            out ColumnDefinition? columnDefinition)
        {
            if (TryMatchColumnOrdinal(sourceDefinition, columnName, out columnDefinition))
            {
                return true;
            }

            string folded = columnName.ToUpperInvariant();
            if (!string.Equals(folded, columnName, StringComparison.Ordinal)
                && TryMatchColumnOrdinal(sourceDefinition, folded, out columnDefinition))
            {
                return true;
            }

            columnDefinition = null;
            return false;
        }

        private static bool TryMatchColumnOrdinal(
            SourceDefinition sourceDefinition,
            string columnName,
            out ColumnDefinition? columnDefinition)
        {
            foreach (KeyValuePair<string, ColumnDefinition> entry in sourceDefinition.Columns)
            {
                if (string.Equals(entry.Key, columnName, StringComparison.Ordinal))
                {
                    columnDefinition = entry.Value;
                    return true;
                }
            }

            columnDefinition = null;
            return false;
        }

        /// <summary>
        /// Classifies sequence assignments in one trigger. <paramref name="isReadOnly"/> is false
        /// only when the assignment sits in a THEN branch whose condition is exactly
        /// <c>:new.col IS NULL</c> or <c>(INSERTING|UPDATING) AND :new.col IS NULL</c> for that
        /// same column. AFTER, statement, and compound triggers contribute nothing.
        /// </summary>
        internal static IReadOnlyList<(string Name, bool IsReadOnly)> ClassifyTrigger(
            string? triggerType,
            string? triggeringEvent,
            string? triggerBody)
        {
            if (!string.IsNullOrWhiteSpace(triggerType)
                && !string.Equals(triggerType.Trim(), "BEFORE EACH ROW", StringComparison.OrdinalIgnoreCase))
            {
                return [];
            }

            if (!string.IsNullOrWhiteSpace(triggeringEvent)
                && triggeringEvent.IndexOf("INSERT", StringComparison.OrdinalIgnoreCase) < 0)
            {
                return [];
            }

            return ClassifyAssignments(triggerBody);
        }

        /// <summary>
        /// Returns column names assigned from a sequence. Quotes are stripped.
        /// Commented-out assignments and assignments inside string literals are ignored.
        /// </summary>
        internal static IReadOnlyList<string> FindTriggerAssignedColumnNames(string triggerBody)
        {
            return ClassifyAssignments(triggerBody)
                .Select(column => column.Name)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();
        }

        /// <summary>
        /// Merges classifications. An unguarded assignment (IsReadOnly true) wins over a guard
        /// for the same column, including across triggers. The dictionary comparer decides
        /// whether <c>id</c> and <c>ID</c> are the same column; callers use ordinal ignore-case.
        /// </summary>
        internal static void MergeTriggerIdentity(
            IDictionary<string, bool> target,
            IEnumerable<(string Name, bool IsReadOnly)> columns)
        {
            foreach ((string name, bool isReadOnly) in columns)
            {
                if (target.TryGetValue(name, out bool existing))
                {
                    target[name] = existing || isReadOnly;
                }
                else
                {
                    target[name] = isReadOnly;
                }
            }
        }

        private static List<(string Name, bool IsReadOnly)> ClassifyAssignments(string? triggerBody)
        {
            if (string.IsNullOrWhiteSpace(triggerBody))
            {
                return [];
            }

            string blanked = BlankCommentsAndLiterals(triggerBody);
            if (Regex.IsMatch(blanked, @"\bCOMPOUND\s+TRIGGER\b", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant))
            {
                return [];
            }

            Dictionary<string, bool> results = new(StringComparer.OrdinalIgnoreCase);
            List<TriggerGuardFrame> stack = new();
            int index = 0;
            while (index < blanked.Length)
            {
                if (char.IsWhiteSpace(blanked[index]))
                {
                    index++;
                    continue;
                }

                if (TryConsumeEndIf(blanked, index, out int afterEndIf))
                {
                    if (stack.Count > 0)
                    {
                        stack.RemoveAt(stack.Count - 1);
                    }

                    index = afterEndIf;
                    continue;
                }

                if (MatchKeyword(blanked, index, "ELSIF"))
                {
                    index = ReplaceGuard(blanked, index + 5, stack);
                    continue;
                }

                if (MatchKeyword(blanked, index, "ELSE"))
                {
                    if (stack.Count > 0)
                    {
                        stack[^1].InThen = false;
                        stack[^1].GuardColumn = null;
                    }

                    index += 4;
                    continue;
                }

                if (MatchKeyword(blanked, index, "IF"))
                {
                    int thenAt = FindKeyword(blanked, index + 2, "THEN");
                    string condition = thenAt < 0 ? string.Empty : blanked[(index + 2)..thenAt];
                    stack.Add(new TriggerGuardFrame
                    {
                        GuardColumn = thenAt < 0 ? null : TryParseGuardColumn(condition),
                        InThen = thenAt >= 0
                    });
                    index = thenAt < 0 ? index + 2 : thenAt + 4;
                    continue;
                }

                if (TryMatchAssignment(blanked, index, out string column, out int next))
                {
                    bool guarded = stack.Any(frame =>
                        frame.InThen
                        && frame.GuardColumn is not null
                        && frame.GuardColumn.Equals(column, StringComparison.OrdinalIgnoreCase));
                    MergeTriggerIdentity(results, [(column, !guarded)]);
                    index = next;
                    continue;
                }

                index++;
            }

            return results.Select(entry => (entry.Key, entry.Value)).ToList();
        }

        private static int ReplaceGuard(string body, int conditionStart, List<TriggerGuardFrame> stack)
        {
            int thenAt = FindKeyword(body, conditionStart, "THEN");
            if (stack.Count > 0)
            {
                string condition = thenAt < 0 ? string.Empty : body[conditionStart..thenAt];
                stack[^1].GuardColumn = thenAt < 0 ? null : TryParseGuardColumn(condition);
                stack[^1].InThen = thenAt >= 0;
            }

            return thenAt < 0 ? conditionStart : thenAt + 4;
        }

        private static bool TryConsumeEndIf(string body, int index, out int next)
        {
            next = index;
            if (!MatchKeyword(body, index, "END"))
            {
                return false;
            }

            int cursor = index + 3;
            while (cursor < body.Length && char.IsWhiteSpace(body[cursor]))
            {
                cursor++;
            }

            if (!MatchKeyword(body, cursor, "IF"))
            {
                return false;
            }

            next = cursor + 2;
            return true;
        }

        private static bool TryMatchAssignment(string body, int index, out string column, out int next)
        {
            column = string.Empty;
            next = index;
            if (index > 0 && IsIdent(body[index - 1]))
            {
                return false;
            }

            Match assignment = AssignmentAt.Match(body, index);
            if (assignment.Success && assignment.Index == index)
            {
                column = FirstCapture(assignment);
                next = assignment.Index + assignment.Length;
                return column.Length > 0;
            }

            Match selectInto = SelectIntoAt.Match(body, index);
            if (selectInto.Success && selectInto.Index == index)
            {
                column = FirstCapture(selectInto);
                next = selectInto.Index + selectInto.Length;
                return column.Length > 0;
            }

            return false;
        }

        private static string FirstCapture(Match match)
        {
            if (match.Groups[1].Success && match.Groups[1].Length > 0)
            {
                return match.Groups[1].Value;
            }

            return match.Groups[2].Value;
        }

        private static string? TryParseGuardColumn(string condition)
        {
            string normalized = Regex.Replace(condition, @"\s+", " ").Trim();
            normalized = StripOuterParentheses(normalized);
            if (normalized.Contains(" OR ", StringComparison.OrdinalIgnoreCase))
            {
                return null;
            }

            Match simple = Regex.Match(
                normalized,
                @"^:new\s*\.\s*(?:""([^""]+)""|([A-Za-z0-9_$#]+))\s+IS\s+NULL$",
                RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
            if (simple.Success)
            {
                return FirstCapture(simple);
            }

            Match flagged = Regex.Match(
                normalized,
                @"^(?:INSERTING|UPDATING)\s+AND\s+:new\s*\.\s*(?:""([^""]+)""|([A-Za-z0-9_$#]+))\s+IS\s+NULL$",
                RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
            if (flagged.Success)
            {
                return FirstCapture(flagged);
            }

            return null;
        }

        private static string StripOuterParentheses(string condition)
        {
            string current = condition.Trim();
            while (current.Length >= 2 && current[0] == '(' && current[^1] == ')')
            {
                int depth = 0;
                bool wrapsAll = true;
                for (int i = 0; i < current.Length; i++)
                {
                    if (current[i] == '(')
                    {
                        depth++;
                    }
                    else if (current[i] == ')')
                    {
                        depth--;
                    }

                    if (depth == 0 && i < current.Length - 1)
                    {
                        wrapsAll = false;
                        break;
                    }
                }

                if (!wrapsAll || depth != 0)
                {
                    break;
                }

                current = current[1..^1].Trim();
            }

            return current;
        }

        private static int FindKeyword(string body, int start, string word)
        {
            for (int i = start; i < body.Length; i++)
            {
                if (MatchKeyword(body, i, word))
                {
                    return i;
                }
            }

            return -1;
        }

        private static bool MatchKeyword(string body, int index, string word)
        {
            if (index < 0 || index + word.Length > body.Length)
            {
                return false;
            }

            if (index > 0 && IsIdent(body[index - 1]))
            {
                return false;
            }

            if (!body.AsSpan(index, word.Length).Equals(word, StringComparison.OrdinalIgnoreCase))
            {
                return false;
            }

            int end = index + word.Length;
            return end >= body.Length || !IsIdent(body[end]);
        }

        private static bool IsIdent(char value)
        {
            return char.IsLetterOrDigit(value) || value is '_' or '$' or '#';
        }

        /// <summary>
        /// Replaces comments and Oracle string literals with spaces so keyword and assignment
        /// scans keep the original indexes. <c>''</c> inside a literal is an escaped quote.
        /// </summary>
        private static string BlankCommentsAndLiterals(string body)
        {
            char[] chars = body.ToCharArray();
            for (int i = 0; i < chars.Length; i++)
            {
                if (i + 1 < chars.Length && chars[i] == '-' && chars[i + 1] == '-')
                {
                    while (i < chars.Length && chars[i] != '\n')
                    {
                        chars[i] = ' ';
                        i++;
                    }
                }
                else if (i + 1 < chars.Length && chars[i] == '/' && chars[i + 1] == '*')
                {
                    chars[i] = ' ';
                    chars[i + 1] = ' ';
                    i += 2;
                    while (i + 1 < chars.Length && !(chars[i] == '*' && chars[i + 1] == '/'))
                    {
                        if (chars[i] != '\n')
                        {
                            chars[i] = ' ';
                        }

                        i++;
                    }

                    if (i < chars.Length)
                    {
                        chars[i] = ' ';
                    }

                    if (i + 1 < chars.Length)
                    {
                        chars[i + 1] = ' ';
                    }
                }
                else if (chars[i] == '\'')
                {
                    chars[i] = ' ';
                    i++;
                    while (i < chars.Length)
                    {
                        if (chars[i] == '\'' && i + 1 < chars.Length && chars[i + 1] == '\'')
                        {
                            chars[i] = ' ';
                            chars[i + 1] = ' ';
                            i += 2;
                            continue;
                        }

                        if (chars[i] == '\'')
                        {
                            chars[i] = ' ';
                            break;
                        }

                        if (chars[i] != '\n')
                        {
                            chars[i] = ' ';
                        }

                        i++;
                    }
                }
            }

            return new string(chars);
        }

        private static DataApiBuilderException MetadataTimeoutException(string operation, Exception inner)
        {
            return new DataApiBuilderException(
                message: $"Oracle metadata command timed out while {operation}. " +
                         "The data-source option command-timeout (seconds; 0 disables the cap) bounds metadata commands.",
                statusCode: HttpStatusCode.ServiceUnavailable,
                subStatusCode: DataApiBuilderException.SubStatusCodes.ErrorInInitialization,
                innerException: inner);
        }

        private sealed class TriggerGuardFrame
        {
            public string? GuardColumn { get; set; }

            public bool InThen { get; set; }
        }
    }
